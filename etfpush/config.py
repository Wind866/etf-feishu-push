# -*- coding: utf-8 -*-
"""全局配置：时区、展示列、指数归类规则、路径。

所有模块只从这里取常量，避免"改了一处忘另一处"。
"""

from datetime import timedelta, timezone
from pathlib import Path

# ---------------------------------------------------------------
# 时区：固定北京时间（UTC+8，无夏令时）
# GitHub runner 默认 UTC，若用 naive datetime，北京 00:00~08:00 触发
# 会把当天数据记到前一天，历史表就错行了。
# ---------------------------------------------------------------
CN_TZ = timezone(timedelta(hours=8))

# ---------------------------------------------------------------
# 路径
# ---------------------------------------------------------------
ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
SNAPSHOT_DIR = ROOT / "snapshots"          # 出图目录（不入库）
HISTORY_PATH = DATA_DIR / "history.json"   # 真实历史（Actions 回写）
DEMO_PATH = DATA_DIR / "demo_history.json" # 演示数据（只读，用于离线调样式）

# ---------------------------------------------------------------
# 展示口径
# ---------------------------------------------------------------
DISPLAY_DAYS = 20          # 图片里展示最近 N 个交易日
METRIC = "主力净流入"       # 指标名，写进历史记录与图片脚注
UNIT = "亿元"

# ---------------------------------------------------------------
# 数据完整性 / 调度
# ---------------------------------------------------------------
MIN_TOTAL_RATIO = 0.90      # 抓到的 ETF 数至少占「代码表有效候选数」的比例
MIN_CHANNEL_COVER = 0.85    # 单通道 ulist 的覆盖率下限（相对有效候选数）
SESSION_MAX_STALE_DAYS = 15 # 行情日期距运行日超过该天数即判为异常（长假也不超过 10 天）
SKIP_WINDOW_HOURS = 3       # 同一数据日期在 N 小时内已推送过就跳过（多档 cron 幂等）

# 列顺序即图片中的列顺序，务必与需求/参考图一致
COLUMNS = [
    "所有ETF",
    "沪深300",
    "中证1000",
    "上证50",
    "中证500",
    "创业板指",
    "科创50",
    "中证A500",
]

# ---------------------------------------------------------------
# 指数归类规则
#   用正则而不是「包含关键词」，因为只用包含会大量误判：
#     创业板50ETF / 创业板新能源ETF / 创业板人工智能ETF  →  全被算进「创业板指」
#     标普500ETF / 沪港深500ETF / 中证500增强ETF        →  全被算进「中证500」
#     沪深300红利ETF / 沪深300价值ETF                   →  全被算进「沪深300」
#   规则是「指数名紧跟 ETF」才算纯被动跟踪，策略型（红利/价值/成长/增强/
#   低波/等权…）一律不计入对应宽基列。顺序敏感，A500 必须排在 500 前面。
# ---------------------------------------------------------------
INDEX_PATTERNS = [
    ("中证A500", r"A500ETF"),
    ("科创50", r"(?:科创50|科创板50)ETF"),
    ("创业板指", r"创业板ETF"),
    ("中证500", r"中证500ETF"),
    ("上证50", r"上证50ETF"),
    ("中证1000", r"中证1000ETF"),
    ("沪深300", r"沪深300ETF"),
]

# 全简称开头的品种（如「500ETF基金」「1000ETF」）按前缀归入对应类别
PREFIX_ALIASES = {
    "A500ETF": "中证A500",
    "1000ETF": "中证1000",
    "300ETF": "沪深300",
    "500ETF": "中证500",
    "50ETF": "上证50",
}

# 货币 / 现金管理类 ETF：主力资金流来自申赎套利，混进「所有ETF」
# 会让合计严重失真（几十亿的假流入），必须剔除。
# 注意不能只写「现金」——「自由现金流ETF」是真实权益品种。
CASH_KEYWORDS = (
    "货币", "添益", "日利", "保证金", "快线", "理财",
    "现金管理", "现金添利", "添天益",
)

# 挂在 ETF 代码段里、但其实不是 ETF 的品种：
#   「汇添富中证500ETF联接(LOF)A」这类场外联接基金可在场内交易，代码段相同
NON_ETF_KEYWORDS = ("联接", "LOF", "分级")

